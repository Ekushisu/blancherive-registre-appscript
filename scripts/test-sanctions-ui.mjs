import assert from 'node:assert/strict';
import vm from 'node:vm';
import {build} from 'esbuild';
let slots=[],cursor=0;
const React={createElement:(type,props,...children)=>({type,props:{...props,children}}),
  useState(initial){const i=cursor++;if(!(i in slots))slots[i]=initial;return [slots[i],value=>{slots[i]=value;}];}};
const ctx=vm.createContext({React,exports:{}});ctx.module={exports:ctx.exports};
const bundle=await build({entryPoints:['ui/src/sanctions.jsx'],bundle:true,write:false,format:'cjs',jsxFactory:'React.createElement'});
vm.runInContext(bundle.outputFiles[0].text,ctx);
const {ChoixSanction,MotifSanction}=ctx.module.exports;
const nodes=node=>Array.isArray(node)?node.flatMap(nodes):node&&typeof node==='object'?[node,...nodes(node.props?.children)]:[];
let value='',tree;
const props={selected:{sanction:{options:[{value:100,label:'100 : simple'},{value:200,label:'200 : récidive'}],libre:true,texte:'Sanction complète'}},type:'amende',value,onChange:v=>{props.value=v;}};
const render=()=>{cursor=0;tree=ChoixSanction(props);return nodes(tree);};
let list=render();
assert.equal(list.find(n=>n.type==='select').props.required,true);
list.find(n=>n.type==='select').props.onChange({target:{value:'200'}});
assert.equal(props.value,'200');
list=render();list.find(n=>n.type==='select').props.onChange({target:{value:'libre'}});
assert.equal(props.value,'','Le passage en saisie libre efface le choix précédent');
list=render();const input=list.find(n=>n.type==='input'&&n.props.type==='number');
assert.ok(input);assert.equal(input.props.step,1);assert.equal(input.props.required,true);
input.props.onChange({target:{value:'350'}});assert.equal(props.value,'350');
slots=[];props.personnalisee=true;props.type='cachot';props.value='';
list=render();assert.equal(list.find(n=>n.type==='input').props.step,'any');
assert.equal(list.some(n=>n.type==='select'),false);
slots=[];props.personnalisee=false;props.selected={sanction:{options:[{value:50,label:'50'}],libre:false}};
list=render();assert.equal(list.find(n=>n.type==='input').props.readOnly,true);
assert.equal(list.find(n=>n.type==='input').props.value,50);
let form={infraction:'Art. 1',montant:'200'};
const motifProps={form,setForm:fn=>{form=fn(form);motifProps.form=form;},infractions:[{label:'Art. 1'},{label:'Art. 2'}],valueKey:'montant'};
list=nodes(MotifSanction(motifProps));
list.find(n=>n.type==='select').props.onChange({target:{value:'Art. 2'}});
assert.equal(form.montant,'');assert.equal(form.infraction,'Art. 2');
list=nodes(MotifSanction(motifProps));
list.find(n=>n.type==='input').props.onChange({target:{checked:true}});
assert.equal(form.personnalisee,true);assert.equal(form.infraction,'');
list=nodes(MotifSanction(motifProps));
assert.equal(list.find(n=>n.type==='textarea').props.required,true);
assert.equal(list.find(n=>n.type==='textarea').props.maxLength,1000);
console.log('Formulaires : choix, saisie libre, heures fractionnaires et réinitialisation des motifs OK.');
